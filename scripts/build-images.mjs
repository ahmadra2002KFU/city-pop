// Generates responsive WebP (+ JPEG/PNG fallback) variants from assets/media.json.
// Outputs are committed so CI does not need to re-encode images.
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import sharp from 'sharp';

const root = resolve(import.meta.dirname, '..');
const sourceDir = resolve(root, 'assets/source');
const outDir = resolve(root, 'public/media');
const config = JSON.parse(readFileSync(resolve(root, 'assets/media.json'), 'utf8'));

mkdirSync(outDir, { recursive: true });
const expected = new Set();
const manifest = {};

for (const entry of config.images) {
  const input = resolve(sourceDir, entry.src);
  let base = sharp(input);
  if (entry.crop) {
    const [left, top, width, height] = entry.crop;
    base = base.extract({ left, top, width, height });
  }
  const { data, info } = await base.toBuffer({ resolveWithObject: true });
  const widths = entry.widths.filter((w) => w <= info.width);
  if (!widths.length) throw new Error(`${entry.id}: every width exceeds the source (${info.width}px)`);
  const fallback = entry.alpha ? 'png' : 'jpg';
  for (const width of widths) {
    const resized = sharp(data).resize({ width, withoutEnlargement: true });
    const webp = `${entry.id}-${width}.webp`;
    await resized.clone().webp({ quality: entry.quality ?? 78, alphaQuality: 90 }).toFile(resolve(outDir, webp));
    expected.add(webp);
  }
  // One fallback file at the middle width keeps old browsers and social crawlers working.
  const fallbackWidth = widths[Math.floor((widths.length - 1) / 2)];
  const fallbackName = `${entry.id}-${fallbackWidth}.${fallback}`;
  const fallbackImage = sharp(data).resize({ width: fallbackWidth });
  await (entry.alpha ? fallbackImage.png({ compressionLevel: 9 }) : fallbackImage.jpeg({ quality: 80, mozjpeg: true })).toFile(resolve(outDir, fallbackName));
  expected.add(fallbackName);
  manifest[entry.id] = {
    width: info.width,
    height: info.height,
    widths,
    fallback: fallbackName,
  };
}

// Remove stale image variants; subfolders such as media/video are managed separately.
for (const entry of readdirSync(outDir, { withFileTypes: true })) {
  if (entry.isFile() && !expected.has(entry.name)) rmSync(resolve(outDir, entry.name));
}

const total = [...expected].reduce((sum, file) => sum + statSync(resolve(outDir, file)).size, 0);
writeFileSync(
  resolve(root, 'content/media.generated.ts'),
  `// Generated by scripts/build-images.mjs from assets/media.json. Do not edit.\n` +
    `export const media = ${JSON.stringify(manifest, null, 2)} as const;\n\n` +
    `export type MediaId = keyof typeof media;\n`,
);
console.log(`Generated ${expected.size} files (${(total / 1024 / 1024).toFixed(2)} MB) for ${config.images.length} images.`);
